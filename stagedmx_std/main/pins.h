#pragma once
// ============ StageDMX 标准版 GPIO ============
// 适用: ESP32-S3-DevKitC-1 (N16R8) 等标准开发板
// 无屏幕、无按键、无电池检测
//
// ==================== v8：两片 SP3485EN，双向 + 独立方向脚 ====================
//
// 硬件：SP3485EN-L/TR **裸片** ×2（不是带单 EN 的模块），每片 4 根信号线全接：
//
//     宇宙1           宇宙2
//     DI  = GPIO17    DI  = GPIO16      ESP 输出 → 芯片 DI
//     RO  = GPIO18    RO  = GPIO15      芯片 RO  → ESP 输入
//     DE  = GPIO4     DE  = GPIO5       方向脚（高 = 驱动总线）
//
// 与本版之前的两点区别（**改代码必须同步改接线，否则发送正常但收不到 / 完全无输出**）：
//   1. **两个宇宙都有了 RO 回程**。老版本 RO 悬空、EN 常驻拉高 —— 是纯发送端，收不到任何东西；
//      现在 RDM 能在**两条**总线上收应答（RDM 需要回程才能工作）。
//   2. **DE 从"两片共用一根 GPIO2"改成每片一根（4 / 5）**。共用一根时没法只让一个宇宙发送，
//      而且 GPIO2 在部分 S3 开发板上挂了板载器件。GPIO2 现在是空闲脚。
//
// ⚠ U1 用 UART1 的**原生引脚**（17 = TX / 18 = RX），省掉 GPIO Matrix 的一层路由；
//   U2 在 ESP32-S3 上**没有原生引脚**（soc/uart_pins.h: U2RXD/U2TXD = -1），
//   15/16 是经 GPIO Matrix 路由的，可以任选空闲脚。

// ---- 宇宙 1（UART1）----
#define DMX_TX_PIN      17    // ESP TXD → 芯片 DI
#define DMX_RX_PIN      18    // ESP RXD ← 芯片 RO
#define DMX_EN_PIN      4     // ESP → 芯片 DE（方向脚）

// ---- 宇宙 2（UART2）----
#define DMX_TX2_PIN     16    // 第二片 DI
#define DMX_RX2_PIN     15    // 第二片 RO
#define DMX_EN2_PIN     5     // 第二片 DE

// 引脚避让（N16R8 模块）：
//   GPIO26~32  → SPI flash
//   GPIO33~37  → Octal PSRAM
//   GPIO19/20  → 原生 USB (D-/D+)
//   GPIO43/44  → UART0（留给控制台兜底）
//   GPIO0/3/45/46 → strapping，不要用作普通输出
//
// 当前占用：4, 5, 15, 16, 17, 18
// 未被占用的脚（可留给按键 / 状态灯 / 扩展）：
//   2, 6, 7, 8, 9, 10, 11, 12, 13, 14, 21, 38, 39, 40, 41, 42, 47, 48
//   （48 = 多数 S3 开发板的板载 RGB LED）

// ==================== SP3485EN 的 /RE 与 DE ====================
// 裸片 SP3485EN 是 8 脚：RO(1) /RE(2) DE(3) DI(4) GND(5) A(6) B(7) VCC(8) ——
// **/RE 和 DE 是两个独立的脚**，电平相反：
//
//     DE = 1 → 驱动总线        DE = 0 → 高阻
//     /RE = 0 → 使能接收       /RE = 1 → 接收高阻
//
// 最省事的接法：**把 /RE 与 DE 短接，一起接到本文件的 EN 脚**。这样
//     GPIO = 1 → 发送（DE=1 驱动、/RE=1 关接收）✔
//     GPIO = 0 → 接收（DE=0 高阻、/RE=0 开接收）✔
// 一颗引脚就是完整的方向控制，firmware 只需驱动 DMX_EN_PIN / DMX_EN2_PIN。
//
// ⚠ 如果 /RE 被单独接走（或直接接地），行为就变了：
//   - /RE 直接接地 = **接收常开**：发送时自己会把自己听回来（半双工回波），
//     RX FIFO 会溢出，EN 每次从收切发时的电平跳变还会被登记成伪 break。
//     这正是下面 DMX_RX_ENABLE 默认关掉的原因之一。
//   - /RE 接单独 GPIO = 想分开控制，需要在 dmx.c 里把 en_pin 拆成 de_pin/re_pin
//     两个字段（结构体注释里已留了提示），并保证两者永不同时有效。

// ==================== 接收（RX）当前是关的 ====================
// dmx.c 里 `DMX_RX_ENABLE = 0`：**帧间不切到接收态，也不给 UART 绑定 RX 引脚**。
// 原因：固件里没有任何代码消费普通 DMX 输入，开着只有副作用（回波 → FIFO 溢出 → 伪 break）。
// 硬件上 RO 接好了不影响，只是固件平时不去听。
//
// ⚠ **RDM 是例外**：RDM 是双向协议，`dmx_rdm_mode()` 会在扫描期间临时绑定 RX 并把
//   EN 交给 UART 的 RTS 自动换向，扫完立刻恢复（见 dmx.c 的 dmx_rdm_mode /
//   dmx_restore_pins）。所以 RDM 不依赖 DMX_RX_ENABLE，但**依赖 RO 真的接着** ——
//   这一版硬件终于接上了。

// ==================== 接线表（每口一片）====================
//   VCC  → 3.3V
//   GND  → GND（两片与 ESP32 必须共地）
//   DI   → ESP GPIO17 (宇宙1) / GPIO16 (宇宙2)   [ESP 输出]
//   RO   → ESP GPIO18 (宇宙1) / GPIO15 (宇宙2)   [ESP 输入]
//   DE   → ESP GPIO4  (宇宙1) / GPIO5  (宇宙2)   [方向；建议 /RE 与 DE 短接]
//   A    → DMX 总线 A (XLR 母头 pin3)
//   B    → DMX 总线 B (XLR 母头 pin2)
//   末端设备 A/B 间并 120Ω 终端电阻
//
// ⚠ A/B 不要接反（DMX 标准: pin2 = B / Data-, pin3 = A / Data+）。
//   接反的表现是"完全收不到"，环回自检时表现为 0 字节回读。
//
// ⚠ DI/RO 接反是**危险**的：两个都是输出，会互相对打（对方是推挽输出时电流很大）。
//   症状：DMX 无输出 + 芯片发烫。上电前务必核对。
